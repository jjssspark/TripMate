/**
 * 입력된 목적지에 맞는 추천 명소. 매칭되지 않으면 빈 배열.
 *
 * 자동완성을 거치지 않고 직접 타이핑하는 경우가 있어 정확히 일치하지 않아도
 * 앞부분 일치("제주" → "제주도")까지는 받아 준다.
 */
export function getRecommendedSpots(destination: string): readonly string[] {
  const query = destination.trim();
  if (!query) return [];

  const exact = RECOMMENDED_SPOTS[query];
  if (exact) return exact;

  const partialKey = Object.keys(RECOMMENDED_SPOTS).find(
    (key) => key.startsWith(query) || query.startsWith(key),
  );
  return partialKey ? RECOMMENDED_SPOTS[partialKey] : [];
}
